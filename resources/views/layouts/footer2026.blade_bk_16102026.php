  <script>
  const footerAccordionHeaders = document.querySelectorAll('.footer-accordion-header');
  const footerMobileQuery = window.matchMedia('(max-width: 767px)');

  function updateFooterAccordionMode() {
    footerAccordionHeaders.forEach(header => {
      const item = header.closest('.footer-accordion-item');
      const controls = item.querySelector('.footer-accordion-content').id;
      if (footerMobileQuery.matches) {
        header.setAttribute('aria-controls', controls);
        header.setAttribute('aria-expanded', String(item.classList.contains('open')));
      } else {
        header.removeAttribute('aria-expanded');
        header.removeAttribute('aria-controls');
      }
    });
  }

  footerAccordionHeaders.forEach(header => {
    header.addEventListener('click', () => {
      if (!footerMobileQuery.matches) return;
      const item = header.closest('.footer-accordion-item');
      item.classList.toggle('open');
      header.setAttribute('aria-expanded', String(item.classList.contains('open')));
    });
  });

  footerMobileQuery.addEventListener('change', updateFooterAccordionMode);
  updateFooterAccordionMode();
  </script>
